#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cargo = resolveCargoCommand();
const parsedArgs = parseWrapperArgs(process.argv.slice(2));
const finalReportPath = resolveOutputPath(parsedArgs.outPath);
const debugReportPath = resolve(repoRoot, "tools/reports/index-build-baseline.debug.tmp.md");
const releaseReportPath = resolve(repoRoot, "tools/reports/index-build-baseline.release.tmp.md");
const passthroughArgs = parsedArgs.passthroughArgs;

mkdirSync(dirname(finalReportPath), { recursive: true });

runBaseline("debug", debugReportPath, false);
runBaseline("release", releaseReportPath, true);

const debugReport = readFileSync(debugReportPath, "utf8");
const releaseReport = readFileSync(releaseReportPath, "utf8");
const combinedReport = [
  "# Index Build Baseline Report",
  "",
  "> Dev-only performance baseline generated by `node tools/index-build-baseline.mjs`.",
  "",
  "This report runs the same index build in debug and release mode without expensive corpus-analysis report rendering. Use release timing for cache decisions.",
  "",
  sectionFromReport(debugReport),
  "",
  sectionFromReport(releaseReport),
  "",
].join("\n");

writeFileSync(finalReportPath, combinedReport);
rmSync(debugReportPath, { force: true });
rmSync(releaseReportPath, { force: true });

console.log(`Wrote index build baseline report: ${finalReportPath}`);

function runBaseline(profileLabel, outPath, release) {
  const args = [
    "run",
    ...(release ? ["--release"] : []),
    "--manifest-path",
    "server/Cargo.toml",
    "--example",
    "index_build_baseline",
    "--",
    "--profile-label",
    profileLabel,
    "--out",
    outPath,
    ...passthroughArgs,
  ];

  const result = spawnSync(cargo, args, {
    cwd: repoRoot,
    stdio: "inherit",
  });

  if (result.error) {
    console.error(`Failed to run ${profileLabel} index build baseline: ${result.error.message}`);
    process.exit(1);
  }

  if ((result.status ?? 1) !== 0) {
    process.exit(result.status ?? 1);
  }
}

function sectionFromReport(report) {
  const marker = "## Profile:";
  const index = report.indexOf(marker);
  return index >= 0 ? report.slice(index).trimEnd() : report.trimEnd();
}

function resolveCargoCommand() {
  if (process.platform === "win32" && process.env.USERPROFILE) {
    const userCargo = resolve(process.env.USERPROFILE, ".cargo", "bin", "cargo.exe");
    if (existsSync(userCargo)) {
      return userCargo;
    }
  }

  return "cargo";
}

function parseWrapperArgs(args) {
  const passthroughArgs = [];
  let outPath;

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--out") {
      const value = args[index + 1];
      if (!value) {
        console.error("--out requires a path");
        process.exit(1);
      }
      outPath = value;
      index += 1;
      continue;
    }

    if (arg === "--profile-label") {
      const value = args[index + 1];
      if (!value) {
        console.error("--profile-label is reserved by the wrapper and requires a value");
        process.exit(1);
      }
      index += 1;
      continue;
    }

    passthroughArgs.push(arg);
  }

  return { outPath, passthroughArgs };
}

function resolveOutputPath(outPath) {
  if (!outPath) {
    return resolve(repoRoot, "tools/reports/index-build-baseline.report.md");
  }

  return resolve(repoRoot, outPath);
}
