use reforger_language_server::parser::parse_source;
use reforger_language_server::syntax::{SyntaxElement, SyntaxKind, SyntaxNode};
use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

const DEFAULT_REPORT_RELATIVE_PATH: &str = "tools/reports/expression-fixtures.report.md";
const DEFAULT_STORAGE_RELATIVE_PATH: &str =
    "Code/User/globalStorage/undefined_publisher.reforger-sript-tools/game-data/scripts";

struct Fixture {
    path: String,
    source: String,
    status: &'static str,
}

fn main() -> Result<(), String> {
    let args = parse_args()?;
    let report = render_report(&args.scripts_path);

    if let Some(parent) = args.out_path.parent() {
        fs::create_dir_all(parent).map_err(|error| {
            format!(
                "Failed to create report folder {}: {error}",
                parent.display()
            )
        })?;
    }
    fs::write(&args.out_path, report).map_err(|error| {
        format!(
            "Failed to write expression fixture report {}: {error}",
            args.out_path.display()
        )
    })?;

    println!(
        "Wrote expression fixture report: {}",
        args.out_path.display()
    );
    Ok(())
}

struct Args {
    scripts_path: PathBuf,
    out_path: PathBuf,
}

fn parse_args() -> Result<Args, String> {
    let mut scripts = None;
    let mut out = None;
    let mut args = env::args().skip(1);

    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--scripts" => {
                let Some(value) = args.next() else {
                    return Err("--scripts requires a path".to_string());
                };
                scripts = Some(PathBuf::from(value));
            }
            "--out" => {
                let Some(value) = args.next() else {
                    return Err("--out requires a path".to_string());
                };
                out = Some(PathBuf::from(value));
            }
            "--help" | "-h" => {
                println!("Usage: cargo run --manifest-path server/Cargo.toml --example expression_report -- [--scripts <path>] [--out <path>]");
                std::process::exit(0);
            }
            _ => return Err(format!("Unknown argument: {arg}")),
        }
    }

    Ok(Args {
        scripts_path: scripts.unwrap_or_else(default_scripts_path),
        out_path: resolve_repo_path(out, DEFAULT_REPORT_RELATIVE_PATH),
    })
}

fn render_report(scripts_path: &Path) -> String {
    let mut report = String::new();
    report.push_str("# Expression Fixture Report\n\n");
    report.push_str("> Human-review output generated by `cargo run --manifest-path server/Cargo.toml --example expression_report`.\n\n");
    report.push_str("This report reviews statement/expression syntax produced inside callable bodies. It is review data only; Workbench remains compiler truth.\n\n");

    for fixture in fixtures(scripts_path) {
        append_fixture_report(&mut report, &fixture);
    }

    report
}

