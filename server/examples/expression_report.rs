fn append_fixture_report(report: &mut String, fixture: &Fixture) {
    let parse = parse_source(&fixture.source);
    let mut counts = BTreeMap::new();
    count_interesting_kinds(&parse.root, &mut counts);

    report.push_str(&format!("## `{}`\n\n", fixture.path));
    report.push_str(&format!("Truth status: `{}`\n\n", fixture.status));
    report.push_str("| Metric | Value |\n");
    report.push_str("| --- | ---: |\n");
    report.push_str(&format!("| Bytes | {} |\n", fixture.source.len()));
    report.push_str(&format!(
        "| Tokens preserved | {} |\n",
        parse.root.token_count()
    ));
    report.push_str(&format!("| Diagnostics | {} |\n", parse.diagnostics.len()));
    report.push_str(&format!(
        "| Max expression depth | {} |\n\n",
        max_expression_depth(&parse.root, 0)
    ));

    if !parse.diagnostics.is_empty() {
        report.push_str("### Diagnostics\n\n");
        for diagnostic in &parse.diagnostics {
            report.push_str(&format!(
                "- `{}` at {}..{}\n",
                diagnostic.message, diagnostic.span.start, diagnostic.span.end
            ));
        }
        report.push('\n');
    }

    report.push_str("### Statement / Expression Counts\n\n");
    report.push_str("| Syntax kind | Count |\n");
    report.push_str("| --- | ---: |\n");
    for (kind, count) in counts {
        report.push_str(&format!("| `{kind}` | {count} |\n"));
    }
    report.push('\n');

    report.push_str("### Body Syntax Outline\n\n");
    append_body_outline(report, &parse.root, 0, 180);
    report.push('\n');
}

fn count_interesting_kinds(node: &SyntaxNode, counts: &mut BTreeMap<String, usize>) {
    if is_statement_or_expression_kind(node.kind) {
        *counts.entry(format!("{:?}", node.kind)).or_default() += 1;
    }
    for child in &node.children {
        if let SyntaxElement::Node(child) = child {
            count_interesting_kinds(child, counts);
        }
    }
}

fn append_body_outline(
    report: &mut String,
    node: &SyntaxNode,
    depth: usize,
    remaining: usize,
) -> usize {
    if remaining == 0 {
        return 0;
    }

    let mut left = remaining;
    if is_statement_or_expression_kind(node.kind) {
        report.push_str(&format!(
            "{}- `{:?}` {}..{}\n",
            "  ".repeat(depth),
            node.kind,
            node.span.start,
            node.span.end
        ));
        left -= 1;
    }

    for child in &node.children {
        if left == 0 {
            break;
        }
        if let SyntaxElement::Node(child) = child {
            left = append_body_outline(report, child, depth + 1, left);
        }
    }
    left
}

fn max_expression_depth(node: &SyntaxNode, current: usize) -> usize {
    let next = if is_expression_kind(node.kind) {
        current + 1
    } else {
        current
    };
    node.children
        .iter()
        .filter_map(|child| match child {
            SyntaxElement::Node(child) => Some(max_expression_depth(child, next)),
            SyntaxElement::Token(_) => None,
        })
        .max()
        .unwrap_or(next)
}

fn is_statement_or_expression_kind(kind: SyntaxKind) -> bool {
    is_statement_kind(kind) || is_expression_kind(kind)
}

fn is_statement_kind(kind: SyntaxKind) -> bool {
    matches!(
        kind,
        SyntaxKind::IfStatement
            | SyntaxKind::ForStatement
            | SyntaxKind::ForeachStatement
            | SyntaxKind::WhileStatement
            | SyntaxKind::DoWhileStatement
            | SyntaxKind::SwitchStatement
            | SyntaxKind::CaseClause
            | SyntaxKind::DefaultClause
            | SyntaxKind::ReturnStatement
            | SyntaxKind::BreakStatement
            | SyntaxKind::ContinueStatement
            | SyntaxKind::DeleteStatement
            | SyntaxKind::ThreadStatement
            | SyntaxKind::EmptyStatement
            | SyntaxKind::LocalDeclStatement
            | SyntaxKind::ExpressionStatement
            | SyntaxKind::ForHeader
            | SyntaxKind::ForInitializer
            | SyntaxKind::ForCondition
            | SyntaxKind::ForIncrement
    )
}

fn is_expression_kind(kind: SyntaxKind) -> bool {
    matches!(
        kind,
        SyntaxKind::Expression
            | SyntaxKind::NameExpression
            | SyntaxKind::LiteralExpression
            | SyntaxKind::ParenthesizedExpression
            | SyntaxKind::UnaryExpression
            | SyntaxKind::BinaryExpression
            | SyntaxKind::AssignmentExpression
            | SyntaxKind::TernaryExpression
            | SyntaxKind::CallExpression
            | SyntaxKind::ArgumentList
            | SyntaxKind::NamedArgument
            | SyntaxKind::MemberAccessExpression
            | SyntaxKind::IndexExpression
            | SyntaxKind::CastExpression
            | SyntaxKind::PostfixExpression
            | SyntaxKind::NewExpression
            | SyntaxKind::InitializerExpression
    )
}

fn default_scripts_path() -> PathBuf {
    if let Some(app_data) = env::var_os("APPDATA") {
        PathBuf::from(app_data).join(DEFAULT_STORAGE_RELATIVE_PATH)
    } else {
        PathBuf::from(DEFAULT_STORAGE_RELATIVE_PATH)
    }
}

fn resolve_repo_path(path: Option<PathBuf>, default_relative_path: &str) -> PathBuf {
    match path {
        Some(path) if path.is_absolute() => path,
        Some(path) => repo_root().join(path),
        None => repo_root().join(default_relative_path),
    }
}

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("server crate should be inside the repository root")
        .to_path_buf()
}
